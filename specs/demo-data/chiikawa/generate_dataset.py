def make_record(index, story, medium, spoilers):
    # Every outline supplies all four medium/spoiler combinations. Alternate
    # sentiment parity so all pairwise combinations have exactly 25 entries.
    media_index = int(medium == "tv")
    positive = (index + media_index + spoilers) % 2 == 0
    variant = index * 4 + media_index * 2 + spoilers
    work = f"ちいかわの{'映画' if medium == 'movie' else '短編アニメ'}"
    parts = [
        f"{work}を見た。{CONTEXTS[variant % len(CONTEXTS)]}",
        story["setup"],
        story["positive" if positive else "negative"],
        MEDIUM_NOTES[medium, positive][index % 5],
        CONCLUSIONS[positive][(index + media_index) % 5],
    ]
    if spoilers:
        # Keep the actual outcome in its original position, with a clear
        # spoiler warning at the beginning of the review.
        if index % 3 == 0:
            parts.append("具体的に印象を決めたのは終盤だった。" + story["ending"])
        else:
            parts.insert(2, "ここからは結末にも触れる。" + story["ending"])
        parts.insert(0, "ネタバレ注意")
    parts.append(NOTICE)
    body = "\n".join(f"<p>{html.escape(p)}</p>" for p in parts)
    return {
        "medium": medium,
        "medium_label": "映画" if medium == "movie" else "テレビアニメ",
        "spoilers": int(spoilers),
        "sentiment": "positive" if positive else "negative",
        "sentiment_label": "肯定的" if positive else "否定的",
        "scenario_id": f"S{index + 1:02d}", "focus": story["focus"],
        "headline": f"{work} — {HEADLINES[positive][(index + media_index) % 5]}",
        "disclosure_position": "tail" if spoilers and index % 3 == 0 else "middle" if spoilers else "none",
        "body": body, "body_characters": len("\n".join(parts)),
        "body_sha256": hashlib.sha256(body.encode("utf-8")).hexdigest(),
    }


def main():
    source = [make_record(i, story, medium, spoilers)
              for i, story in enumerate(STORIES)
              for medium in ("movie", "tv") for spoilers in (False, True)]
    # Deterministic interleaving: do not group all examples by their answer label.
    records = [source[(i * 37) % 100] for i in range(100)]
    blocks, manifest = [], []
    for n, record in enumerate(records, 1):
        article_id = f"CKW-{n:04d}"
        basename = f"chiikawa-demo-{n:04d}"
        title = f"{record['headline']} [{article_id}]"
        date = datetime(2025, 1, 1, 9) + timedelta(days=(n * 73) % 500, hours=n % 10)
        blocks.append("\n".join([
            f"TITLE: {title}", f"BASENAME: {basename}", "STATUS: Draft",
            "ALLOW COMMENTS: 0", "ALLOW PINGS: 0", "CONVERT BREAKS: 0",
            f"PRIMARY CATEGORY: {record['medium_label']}", f"DATE: {date:%m/%d/%Y %I:%M:%S %p}",
            "-----", "BODY:", record["body"],
            "-----", "EXTENDED BODY:", "", "-----", "EXCERPT:", "",
            "-----", "KEYWORDS:", "", "-----", "--------", "",
        ]))
        manifest.append({
            "id": article_id, "basename": basename, "title": title,
            "site_name": "アニメの感想",
            **{k: v for k, v in record.items() if k not in ("headline", "body")},
            "date": date.isoformat(sep=" "), "status": "Draft",
        })

    assert len(STORIES) == 25 and len(records) == 100
    assert len({r["body_sha256"] for r in records}) == 100
    for key in ("medium", "spoilers", "sentiment"):
        assert sorted(Counter(r[key] for r in records).values()) == [50, 50], key
    for first, second in (("medium", "spoilers"), ("medium", "sentiment"), ("spoilers", "sentiment")):
        assert set(Counter((r[first], r[second]) for r in records).values()) == {25}
    cells = Counter((r["medium"], r["spoilers"], r["sentiment"]) for r in records)
    assert sorted(cells.values()) == [12, 12, 12, 12, 13, 13, 13, 13]
    for r in records:
        assert NOTICE in html.unescape(r["body"])
        assert ("終盤だった" in r["body"] or "結末にも触れる" in r["body"]) == bool(r["spoilers"])
        assert r["body"].count("ネタバレ注意") == r["spoilers"]

    (ROOT / "chiikawa-reviews-100.txt").write_text("\n".join(blocks), encoding="utf-8")
    with (ROOT / "manifest.csv").open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(manifest[0]))
        writer.writeheader()
        writer.writerows(manifest)

    queries = []
    for medium, label in (("movie", "映画"), ("tv", "テレビアニメ")):
        for spoilers in (False, True):
            for sentiment, opinion in (("positive", "全体として楽しめたと評価している"), ("negative", "全体としては不満があり、評価が厳しい")):
                ids = [r["id"] for r in manifest
                       if (r["medium"], r["spoilers"], r["sentiment"]) == (medium, int(spoilers), sentiment)]
                query = f"ちいかわの{label}の感想で、{'結末の具体的な展開まで書いており' if spoilers else '物語の結末や種明かしには触れず'}、{opinion}記事"
                queries.append({"query": query, "expected_count": len(ids), "expected_ids": ids})
